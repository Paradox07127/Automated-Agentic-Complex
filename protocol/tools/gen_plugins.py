"""Write or check the daemon, web and shell copies of the static plug-in registry."""
import argparse
import json
from pathlib import Path
import pprint

ROOT = Path(__file__).resolve().parents[2]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    args = parser.parse_args()
    entries = json.loads((ROOT / "protocol/plugins/plugins.json").read_text(encoding="utf-8"))
    notice = "Generated by protocol/tools/gen_plugins.py from protocol/plugins/plugins.json; do not edit."
    ts = f"// {notice}\nexport const PLUGINS = " + json.dumps(entries, indent=2) + " as const;\n\nexport type PluginId = typeof PLUGINS[number]['id'];\n"
    outputs = {
        "agent/agentd/infra/plugins_generated.py": f"# {notice}\nPLUGINS = " + pprint.pformat(entries, sort_dicts=False, width=110) + "\n",
        "web/src/bridge/plugins.generated.ts": ts,
        "app/electron/src/common/plugins.generated.ts": ts,
    }
    stale = False
    for name, content in outputs.items():
        path = ROOT / name
        if args.write:
            path.write_text(content, encoding="utf-8")
        elif not path.is_file() or path.read_text(encoding="utf-8") != content:
            print(f"stale: {name}; run python3 -I protocol/tools/gen_plugins.py --write")
            stale = True
    return int(stale)


if __name__ == "__main__":
    raise SystemExit(main())

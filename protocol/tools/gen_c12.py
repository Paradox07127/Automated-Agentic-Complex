"""Writes the two platform helpers' C12 op tables from protocol/C12-platform-helper/ops.json.

Usage: python3 -I protocol/tools/gen_c12.py --write | --check
"""

from pathlib import Path
import json
import re
import sys

ROOT = Path(__file__).resolve().parents[2]
OPS = ROOT / "protocol" / "C12-platform-helper" / "ops.json"
SWIFT = ROOT / "app" / "helpers" / "mac" / "Sources" / "HelperCore" / "OpTable.generated.swift"
CPP = ROOT / "app" / "helpers" / "windows" / "src" / "ops_table.generated.h"
NOTICE = "Generated by protocol/tools/gen_c12.py from protocol/C12-platform-helper/ops.json; do not edit."
PLATFORMS = {("macos", "windows"): "both", ("macos",): "mac", ("windows",): "windows"}
ARRAY = re.compile(r"^arr<(.+)>$")


def load():
    spec = json.loads(OPS.read_text(encoding="utf-8"))
    ops = [(name, PLATFORMS[tuple(sorted(op["platforms"]))], op.get("params", {}), op.get("params_optional", {}),
            op.get("params_one_of", [])) for name, op in spec["ops"].items()]
    used = set()

    def note(kind):
        kind = kind.rstrip("?")
        array = ARRAY.match(kind)
        if array:
            note(array.group(1))
        elif kind in spec["types"]:
            used.add(kind)

    for _, _, params, optional, _ in ops:
        for kind in list(params.values()) + list(optional.values()):
            note(kind)
    types = [(name, shape.get("fields", {}), shape.get("optional", {})) for name, shape in spec["types"].items()
             if name in used]
    limits = [(name, key, value) for name, op in spec["ops"].items() for key, value in op.get("limits", {}).items()]
    return ops, types, spec["secure_keywords"], limits


def quoted(names):
    return ", ".join(f'"{name}"' for name in names)


def camel(*parts):
    words = [w for part in parts for w in re.split(r"[._]", part)]
    return words[0] + "".join(w[:1].upper() + w[1:] for w in words[1:])


def render_swift(ops, types, keywords, limits):
    def fields(table):
        return "[" + ", ".join(f'("{name}", "{kind}")' for name, kind in table.items()) + "]"

    out = [f"// {NOTICE}", "",
           '/// ops.json "ops" in its order: name, the platforms whose `hello.ops` list it, params, params_optional, params_one_of.',
           "enum C12Ops {",
           "    enum Platforms { case both, mac, windows }",
           "",
           "    struct Op {",
           "        let name: String",
           "        let platforms: Platforms",
           "        let params: [(name: String, kind: String)]",
           "        let optional: [(name: String, kind: String)]",
           "        let oneOf: [String]",
           "    }",
           "",
           "    struct Shape {",
           "        let fields: [(name: String, kind: String)]",
           "        let optional: [(name: String, kind: String)]",
           "    }",
           "",
           "    static let ops: [Op] = ["]
    for name, platforms, params, optional, one_of in ops:
        out.append(f'        Op(name: "{name}", platforms: .{platforms}, params: {fields(params)}, optional: {fields(optional)}, '
                   f"oneOf: [{quoted(one_of)}]),")
    out += ["    ]", "", '    /// ops.json "types" that params use.', "    static let paramTypes: [String: Shape] = ["]
    for name, required, optional in types:
        out.append(f'        "{name}": Shape(fields: {fields(required)}, optional: {fields(optional)}),')
    out += ["    ]", "",
            '    /// ops.json "secure_keywords": lower case; a node whose role, title or description holds one is a password control.',
            f"    static let secureKeywords = [{quoted(keywords)}]", "",
            '    /// ops.json "limits": the default budgets of the ops, by op and name.', "    enum Limits {"]
    for name, key, value in limits:
        out.append(f"        static let {camel(name, key)} = {value}")
    out += ["    }", "}", ""]
    return "\n".join(out)


def render_cpp(ops, types, keywords, limits):
    def fields(table):
        return "{" + ", ".join(f'{{"{name}", "{kind}"}}' for name, kind in table.items()) + "}"

    out = [f"// {NOTICE}", "#pragma once", "", "#include <cstddef>", "#include <vector>", "", "namespace c12_generated {", "",
           "enum class Platforms { both, mac, windows };", "",
           "struct Field {", "    const char* name;", "    const char* kind;", "};", "",
           "struct Op {", "    const char* name;", "    Platforms platforms;", "    std::vector<Field> params;",
           "    std::vector<Field> optional;", "    std::vector<const char*> one_of;", "};", "",
           "struct Type {", "    const char* name;", "    std::vector<Field> fields;", "    std::vector<Field> optional;", "};",
           "",
           '// ops.json "ops" in its order: name, the platforms whose hello.ops list it, params, params_optional, params_one_of.',
           "inline const std::vector<Op>& ops() {", "    static const std::vector<Op> table = {"]
    for name, platforms, params, optional, one_of in ops:
        out.append(f'        {{"{name}", Platforms::{platforms}, {fields(params)}, {fields(optional)}, '
                   f"{{{quoted(one_of)}}}}},")
    out += ["    };", "    return table;", "}", "", '// ops.json "types" that params use.',
            "inline const std::vector<Type>& param_types() {", "    static const std::vector<Type> table = {"]
    for name, required, optional in types:
        out.append(f'        {{"{name}", {fields(required)}, {fields(optional)}}},')
    out += ["    };", "    return table;", "}", "",
            '// ops.json "secure_keywords": lower case; a control whose role, title or description holds one is a password',
            "// control.",
            "inline const std::vector<const wchar_t*>& secure_keywords() {",
            "    static const std::vector<const wchar_t*> table = {" + ", ".join(f'L"{k}"' for k in keywords) + "};",
            "    return table;", "}", "",
            '// ops.json "limits": the default budgets of the ops, by op and name.', "namespace limits {"]
    for name, key, value in limits:
        out.append(f"constexpr size_t {name.replace('.', '_')}_{key} = {value};")
    out += ["}  // namespace limits", "", "}  // namespace c12_generated", ""]
    return "\n".join(out)


def main(argv):
    if argv not in (["--write"], ["--check"]):
        print(__doc__.strip().splitlines()[-1], file=sys.stderr)
        return 2
    spec = load()
    outputs = {SWIFT: render_swift(*spec), CPP: render_cpp(*spec)}
    stale = [path for path, text in outputs.items() if not path.is_file() or path.read_text(encoding="utf-8") != text]
    if argv == ["--write"]:
        for path in stale:
            path.write_text(outputs[path], encoding="utf-8", newline="\n")
        return 0
    for path in stale:
        print(f"stale: {path.relative_to(ROOT)}; run python3 -I protocol/tools/gen_c12.py --write", file=sys.stderr)
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))

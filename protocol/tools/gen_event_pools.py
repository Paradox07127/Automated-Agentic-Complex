"""Writes the player core's agentd event pool table from protocol/C3-host-ipc/event-pools.json "keys".

Usage: python3 -I protocol/tools/gen_event_pools.py --write | --check
"""

from pathlib import Path
import json
import sys

ROOT = Path(__file__).resolve().parents[2]
TABLE = ROOT / "protocol" / "C3-host-ipc" / "event-pools.json"
CORE = ROOT / "private" / "renderer" / "core"
HEADER = CORE / "src" / "event_pools.generated.h"
NOTICE = "Generated by protocol/tools/gen_event_pools.py from protocol/C3-host-ipc/event-pools.json; do not edit."
SCHEMA = "agentic-complex-event-pools/v1"


def render(keys):
    for key in keys:
        if not isinstance(key, str) or not key or not all(" " <= c <= "~" and c not in '"\\' for c in key):
            raise ValueError(f"{key!r} is not a printable ASCII event key")
    if len(set(keys)) != len(keys):
        raise ValueError("event-pools.json repeats a key")
    out = [f"/* {NOTICE} */", "#ifndef PC_EVENT_POOLS_GENERATED_H", "#define PC_EVENT_POOLS_GENERATED_H", "",
           f"#define PC_EVENT_POOL_COUNT {len(keys)}", "",
           '/* event-pools.json "keys" in its order: the event pools agentd draws from, which a motion override may fill',
           " * where the pack has none. */",
           "static const char* const pc_event_pools[PC_EVENT_POOL_COUNT] = {"]
    out += [f'    "{key}",' for key in keys]
    out += ["};", "", "#endif /* PC_EVENT_POOLS_GENERATED_H */", ""]
    return "\n".join(out)


def main(argv):
    if argv not in (["--write"], ["--check"]):
        print(__doc__.strip().splitlines()[-1], file=sys.stderr)
        return 2
    # A public checkout has no renderer sources: without the player core there is nothing to generate.
    if not CORE.is_dir():
        return 0
    document = json.loads(TABLE.read_text(encoding="utf-8"))
    if document.get("schema") != SCHEMA:
        raise ValueError(f"{TABLE.relative_to(ROOT)} is not {SCHEMA}")
    text = render(document["keys"])
    stale = not HEADER.is_file() or HEADER.read_text(encoding="utf-8") != text
    if argv == ["--write"]:
        if stale:
            HEADER.write_text(text, encoding="utf-8", newline="\n")
        return 0
    if stale:
        print(f"stale: {HEADER.relative_to(ROOT)}; run python3 -I protocol/tools/gen_event_pools.py --write", file=sys.stderr)
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))

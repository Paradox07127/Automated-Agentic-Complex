"""Writes host-common's render settings table from protocol/C3-host-ipc/capabilities.json "render_settings".

Usage: python3 -I protocol/tools/gen_render_table.py --write | --check
"""

from pathlib import Path
import json
import sys

ROOT = Path(__file__).resolve().parents[2]
TABLE = ROOT / "protocol" / "C3-host-ipc" / "capabilities.json"
COMMON = ROOT / "private" / "renderer" / "common"
HEADER = COMMON / "include" / "hc_render_table.generated.h"
NOTICE = "Generated by protocol/tools/gen_render_table.py from protocol/C3-host-ipc/capabilities.json; do not edit."
PREFIX = "--agentic-complex-"
MODES = {"applied": "HC_RENDER_APPLIED", "fixed": "HC_RENDER_FIXED", "ignored": "HC_RENDER_IGNORED"}


def render(rows):
    out = [f"/* {NOTICE} */", "#ifndef HC_RENDER_TABLE_GENERATED_H", "#define HC_RENDER_TABLE_GENERATED_H", "",
           '#include "hc_render_settings.h"', "",
           f"#define HC_RENDER_TABLE_ROWS {len(rows)}", "",
           '/* capabilities.json "render_settings" in its order: the launch option without --agentic-complex-, its',
           " * pipeline.render.unsupported name, then what the macOS host and efw do with it, indexed by hc_render_backend. */",
           "static const hc_render_row hc_render_table[HC_RENDER_TABLE_ROWS] = {"]
    for name, row in rows:
        if not name.startswith(PREFIX):
            raise ValueError(f"{name} is not a --agentic-complex- option")
        short = name[len(PREFIX):]
        out.append(f'    {{"{short}", "{short.replace("-", "_")}", {{{MODES[row["mac"]]}, {MODES[row["windows"]]}}}}},')
    out += ["};", "", "#endif /* HC_RENDER_TABLE_GENERATED_H */", ""]
    return "\n".join(out)


def main(argv):
    if argv not in (["--write"], ["--check"]):
        print(__doc__.strip().splitlines()[-1], file=sys.stderr)
        return 2
    # A public checkout has no renderer sources: without host-common there is nothing to generate.
    if not COMMON.is_dir():
        return 0
    text = render(list(json.loads(TABLE.read_text(encoding="utf-8"))["render_settings"].items()))
    stale = not HEADER.is_file() or HEADER.read_text(encoding="utf-8") != text
    if argv == ["--write"]:
        if stale:
            HEADER.write_text(text, encoding="utf-8", newline="\n")
        return 0
    if stale:
        print(f"stale: {HEADER.relative_to(ROOT)}; run python3 -I protocol/tools/gen_render_table.py --write", file=sys.stderr)
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))

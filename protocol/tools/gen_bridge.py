"""Writes the per-surface ui-bridge tables for TS from protocol/ui-bridge/ops.json and onboarding-ops.json.

Usage: python3 -I protocol/tools/gen_bridge.py --write | --check
"""

from pathlib import Path
import json
import sys

ROOT = Path(__file__).resolve().parents[2]
BRIDGE = ROOT / "protocol" / "ui-bridge"
TS = ROOT / "web" / "src" / "bridge" / "surfaces.generated.ts"
SURFACES = ("main", "stack", "onboarding")
HEADER = "// Generated by protocol/tools/gen_bridge.py from protocol/ui-bridge/ops.json and onboarding-ops.json; do not edit."


def load():
    ops = json.loads((BRIDGE / "ops.json").read_text(encoding="utf-8"))
    onboarding = json.loads((BRIDGE / "onboarding-ops.json").read_text(encoding="utf-8"))
    return ops, onboarding["ops"]


def wrap(items, indent, quote, width):
    lines, line = [], indent
    for item in items:
        piece = f"{quote}{item}{quote},"
        if line != indent and len(line) + 1 + len(piece) > width:
            lines.append(line)
            line = indent
        line += piece if line == indent else " " + piece
    lines.append(line)
    return lines


def ts_list(name, items, doc=None):
    out = [f"/** {doc} */"] if doc else []
    return out + [f"export const {name}: readonly string[] = ["] + wrap(items, "  ", "'", 120) + ["];", ""]


def ts_bit(value):
    return f"'{value}'" if isinstance(value, str) else "true" if value else "false"


def render_ts(file, onboarding):
    out = [HEADER, "import type { Capabilities, Surface } from './protocol';", ""]
    out += ts_list("BRIDGE_OPS", file["ops"] + onboarding, "Every op of `AgenticComplexBridge`.")
    out += ts_list("INTERNAL_OPS", file["internal"], "Ops only the native shim sends; they are not bridge members.")
    out += ["/** Ops each surface may send. */", "export const SURFACE_OPS: Readonly<Record<Surface, readonly string[]>> = {"]
    for surface in SURFACES:
        out += [f"  {surface}: ["] + wrap(file["surfaces"][surface], "    ", "'", 120) + ["  ],"]
    out += ["};", ""]
    out += ts_list("WATCH_OPS", file["kinds"]["watch"], "`on<Name>` subscriptions; `events.unsubscribe` ends them.")
    out += ts_list("SYNC_OPS", file["kinds"]["sync"], "Void ops sent without waiting for the reply.")
    out += ts_list("STREAM_OPS", file["kinds"]["stream"], "Event streams; `<name>.unsubscribe` ends them.")
    out += ts_list("DESKTOP_OPS", file["desktop"], "Ops served only when the native host has a desktop.")
    out += [
        "/** `'host:avatar'`: true only when the native host has an avatar; `'host:actionLoop'`: only when it lists C3 `action_loop`. */",
        "export type SurfaceCapabilities = { readonly [K in keyof Capabilities]: boolean | 'host:avatar' | 'host:actionLoop' };",
        "",
        "export const SURFACE_CAPABILITIES: Readonly<Record<Surface, SurfaceCapabilities>> = {",
    ]
    for surface in SURFACES:
        bits = file["capabilities"][surface]
        out += [f"  {surface}: {{"] + [f"    {name}: {ts_bit(value)}," for name, value in bits.items()] + ["  },"]
    out += ["};", ""]
    return "\n".join(out)


def main(argv):
    if argv not in (["--write"], ["--check"]):
        print(__doc__.strip().splitlines()[-1], file=sys.stderr)
        return 2
    file, onboarding = load()
    outputs = {TS: render_ts(file, onboarding)}
    stale = [path for path, text in outputs.items() if not path.is_file() or path.read_text(encoding="utf-8") != text]
    if argv == ["--write"]:
        for path in stale:
            path.write_text(outputs[path], encoding="utf-8")
        return 0
    for path in stale:
        print(f"stale: {path.relative_to(ROOT)}", file=sys.stderr)
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))

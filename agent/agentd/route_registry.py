PLUGIN_PREFIXES = {}
for entry in PLUGINS:
    for prefix in entry["agentd"]["routes"]:
        PLUGIN_PREFIXES.setdefault(prefix, []).append(entry["id"])

# Text chat and its topic lifecycle also run on a standalone local harness.
for prefix in ("/say", "/conversations", "/turn/cancel"):
    PLUGIN_PREFIXES[prefix].append("harness_bridge")


@dataclass(frozen=True, slots=True)
class Route:
    method: str
    path: str | re.Pattern  # a literal path, or a pattern the whole path must match
    tokens: tuple
    ui_class: str  # protocol/ui-bridge/routes.json "class"
    surfaces: tuple  # web surfaces that may send it
    templates: tuple = ()  # ":param" forms of a pattern path, one per alternation
    owner: str | None = None
    action: str | None = None  # the Handler method that answers an api.handler route; it gets the pattern's groups
    summary: str = ""
    spec: str | None = None  # None: no prose spec anywhere yet
    response: str | None = None
    request: str | None = None
    stream: str | None = None
    plugin: str | None = field(init=False, default=None)
    shared_plugins: tuple = field(init=False, default=())

    def __post_init__(self):
        # A more specific prefix owns routes such as /observation/briefs.
        path = self.templates[0] if self.templates else self.path
        while path:
            if path in PLUGIN_PREFIXES:
                owners = PLUGIN_PREFIXES[path]
                if len(owners) == 1:
                    object.__setattr__(self, "plugin", owners[0])
                else:
                    object.__setattr__(self, "shared_plugins", tuple(owners))
                break
            path = path.rpartition("/")[0]


